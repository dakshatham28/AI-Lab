# Agent function table
agent_table = {
    ('Clean', 'A'): 'MoveRight',
    ('Clean', 'B'): 'MoveLeft',
    ('Dirty', 'A'): 'Suck',
    ('Dirty', 'B'): 'Suck',
}

# Vacuum cleaner class
class VacuumCleaner:
    def __init__(self, location='A', status='Clean'):
        self.location = location
        self.status = status

    def percept(self):
        return self.status

    def act(self, action):
        if action == 'MoveRight':
            self.location = 'B'
        elif action == 'MoveLeft':
            self.location = 'A'
        elif action == 'Suck':
            self.status = 'Clean'

# Table-driven agent function
def table_driven_agent(percept):
    return agent_table.get(percept, 'NoOp')

# Main simulation loop
if __name__ == "__main__":
    vacuum = VacuumCleaner(location='A', status='Dirty')

